"""Generate the FOTA signing keypair (ECDSA NIST P-256).

Outputs:
  keys/fota_private.pem               PRIVATE key (gitignored, never committed)
  keys/fota_public.pem                reference copy (regenerable)
  tools/fota_public.pem               canonical public key for the host tool
  Bootloader/Core/Inc/bootloader_key.h  public key as a C array for the MCU

Run from anywhere: paths are resolved relative to the repository root.
"""

import argparse
import hashlib
import sys
from pathlib import Path

import ecdsa

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--force", action="store_true", help="overwrite existing keys")
    args = ap.parse_args()

    priv_path = ROOT / "keys" / "fota_private.pem"
    if priv_path.exists() and not args.force:
        sys.exit(f"refusing to overwrite {priv_path} (use --force)")

    sk = ecdsa.SigningKey.generate(curve=ecdsa.NIST256p)
    vk = sk.get_verifying_key()

    (ROOT / "keys").mkdir(exist_ok=True)
    priv_path.write_bytes(sk.to_pem())
    (ROOT / "keys" / "fota_public.pem").write_bytes(vk.to_pem())
    (ROOT / "tools" / "fota_public.pem").write_bytes(vk.to_pem())

    pub = vk.to_string()  # 64 B: X||Y big-endian, micro-ecc layout
    assert len(pub) == 64
    fingerprint = hashlib.sha256(pub).hexdigest()[:16]
    rows = []
    for i in range(0, 64, 8):
        rows.append("\t" + ", ".join(f"0x{b:02X}U" for b in pub[i : i + 8]) + ",")
    header = (
        "/* bootloader_key.h - FOTA signing PUBLIC key (ECDSA NIST P-256)\n"
        " * Layout: X||Y, 32B each, big-endian (micro-ecc native).\n"
        " * GENERATED by tools/keygen.py - do not edit by hand.\n"
        f" * Key fingerprint (first 16 hex of SHA-256 over the 64 key bytes): {fingerprint}\n"
        " * The matching private key never enters the repository. */\n"
        "\n"
        "#ifndef BOOTLOADER_KEY_H_\n"
        "#define BOOTLOADER_KEY_H_\n"
        "\n"
        "#include <stdint.h>\n"
        "\n"
        "static const uint8_t BL_PUBLIC_KEY_XY[64] =\n"
        "{\n" + "\n".join(rows) + "\n};\n"
        "\n"
        "#endif /* BOOTLOADER_KEY_H_ */\n"
    )
    (ROOT / "Bootloader" / "Core" / "Inc" / "bootloader_key.h").write_text(header)

    print(f"private key : {priv_path}  (KEEP SECRET - gitignored)")
    print(f"public key  : tools/fota_public.pem (host) + Bootloader/Core/Inc/bootloader_key.h (MCU)")
    print(f"fingerprint : {fingerprint}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
